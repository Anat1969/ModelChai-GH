// Bundles each function's src into its deployable index.ts, so the server runs the very
// same recipe schema and rules as the browser. npm packages stay external as pinned Deno npm: specifiers.
import { build } from 'esbuild'
import { readFileSync } from 'node:fs'

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const versions = { ...pkg.dependencies, ...pkg.devDependencies }
const EXTERNAL = ['@anthropic-ai/sdk', '@supabase/supabase-js', 'zod']

const npmSpecifiers = {
  name: 'npm-specifiers',
  setup(b) {
    b.onResolve({ filter: new RegExp(`^(${EXTERNAL.map((e) => e.replace('/', '\\/')).join('|')})$`) }, (args) => ({
      path: `npm:${args.path}@${versions[args.path]}`,
      external: true,
    }))
  },
}

for (const fn of ['concept-to-recipe', 'concept-post']) {
await build({
  entryPoints: [`supabase/functions/${fn}/src/handler.ts`],
  outfile: `supabase/functions/${fn}/index.ts`,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  loader: { '.md': 'text', '.json': 'json' },
  plugins: [npmSpecifiers],
  banner: { js: '// @ts-nocheck\n// Generated by scripts/build-function.mjs from ./src. Do not edit by hand.' },
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
})
console.log(`built supabase/functions/${fn}/index.ts`)
}
