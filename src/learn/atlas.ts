export const modelById = (id: string) => MODELS.find((m) => m.id === id)

export interface ModelWithUses extends Model {
  uses: UseFit[]
}

export const withUses = (m: Model, limit = 4): ModelWithUses => ({ ...m, uses: usesFor(m.traits, limit) })

/** Models ranked for a use, with the reasons. The bridge from a need to concepts. */
export function modelsForUse(useId: string, limit = 6) {
  return MODELS.map((m) => ({ model: m, fit: usesFor(m.traits, 99).find((f) => f.use.id === useId) }))
    .filter((x): x is { model: Model; fit: UseFit } => !!x.fit)
    .sort((a, b) => b.fit.score - a.fit.score || (a.model.fit.level === 'full' ? -1 : 1))
    .slice(0, limit)
}

